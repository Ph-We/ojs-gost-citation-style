        'issued' => ['raw' => '2026-01-01'],
        'accessed' => ['raw' => '2026-11-06'],
        'author' => array_slice($authorList, 0, $authorCount),
    ];
    foreach ($remove as $variable) {
        unset($data[$variable]);
    }
    return json_decode(json_encode($data, JSON_THROW_ON_ERROR), false, 512, JSON_THROW_ON_ERROR);
};

